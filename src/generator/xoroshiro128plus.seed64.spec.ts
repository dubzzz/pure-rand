import { describe, it, expect } from 'vitest';
import * as fc from 'fast-check';

import type { Seed64 } from '../types/Seed64';
import { seed64FromHex } from '../seed/seed64FromHex';
import { xoroshiro128plus, xoroshiro128plusFromState } from './xoroshiro128plus';
import * as p from './Seed64.properties';
import { generateN } from '../utils/generateN';

describe('xoroshiro128plus with Seed64', () => {
  it.each([
    [
      '0000000000000000',
      [483865507, 1747211118, 3822025699, 2636587237, 1661686461, 3021111331, 2657678885, 996699727],
    ],
    ['0000000000000001', [4002498856, 2582627400, 2957369732, 990741077, 3727276589, 917576201, 689736659, 3808371023]],
    [
      '0000000100000000',
      [4208508533, 3761654109, 1171735378, 4116798379, 3862641998, 2626882334, 1565690495, 4241723986],
    ],
    [
      '0123456789abcdef',
      [3643898672, 2019709896, 853015263, 267197769, 2579654960, 3712851444, 2785446902, 4170874163],
    ],
    [
      'ffffffffffffffff',
      [4149980905, 4151286192, 1381649032, 1278543674, 296774522, 3443532630, 2248904282, 4107888903],
    ],
  ])('Should match the reference C stream for seed=%s', (hex, expected) => {
    // Generated by composing the authors' splitmix64.c and xoroshiro128plus.c.
    // Read SplitMix64 twice into s[0] and s[1], then keep each next() output's low word.
    const rng = xoroshiro128plus(seed64FromHex(hex));
    expect(generateN(rng, expected.length)).toEqual(expected.map((value) => value | 0));
  });

  it('Should initialize both state words from SplitMix64', () => {
    // First two outputs of the reference SplitMix64 C implementation for seed=0.
    expect(xoroshiro128plus([0, 0]).getState()).toEqual(
      [0xe220a839, 0x7b1dcdaf, 0x6e789e6a, 0xa1b965f4].map((value) => value | 0),
    );
  });

  it('Should use the high seed word', () => {
    const low = xoroshiro128plus(seed64FromHex('0000000000000000'));
    const high = xoroshiro128plus(seed64FromHex('0000000100000000'));
    expect(low.getState()).not.toEqual(high.getState());
  });

  it('Should use distinct initialization rules for numeric and Seed64 seeds', () => {
    expect(xoroshiro128plus([0, 42]).getState()).not.toEqual(xoroshiro128plus(42).getState());
  });

  it('Should reject invalid Seed64 words', () => {
    expect(() => xoroshiro128plus([-1, 0])).toThrow(RangeError);
    expect(() => xoroshiro128plus([0, 2 ** 32])).toThrow(RangeError);
    expect(() => xoroshiro128plus([0, 0.5])).toThrow(RangeError);
    expect(() => xoroshiro128plus([0] as unknown as Seed64)).toThrow(RangeError);
  });

  it('Should return the same sequence given the same seed', () =>
    fc.assert(p.sameSeed64SameSequences(xoroshiro128plus)));
  it('Should support cloning and state restoration', () =>
    fc.assert(p.cloneAndRestoreSeed64(xoroshiro128plus, xoroshiro128plusFromState)));
  it('Should not depend on ordering between jump and next', () => fc.assert(p.seed64NoOrderNextJump(xoroshiro128plus)));
  it('Should not mutate or retain the seed tuple', () => fc.assert(p.doesNotRetainSeed64(xoroshiro128plus)));
});
