import { describe, it, expect } from 'vitest';
import * as fc from 'fast-check';

import type { Seed64 } from '../types/Seed64';
import { seed64FromHex } from '../seed/seed64FromHex';
import { xorshift128plus, xorshift128plusFromState } from './xorshift128plus';
import * as p from './Seed64.properties';
import { generateN } from '../utils/generateN';

describe('xorshift128plus with Seed64', () => {
  it.each([
    [
      '0000000000000000',
      [483865507, 3008884295, 1673238366, 4258738226, 1197091817, 2362142847, 2068017335, 835219444],
    ],
    [
      '0000000000000001',
      [4002498856, 2443143692, 3990635857, 3023627068, 1297157282, 2683432099, 2791591224, 2455932287],
    ],
    [
      '0000000100000000',
      [4208508533, 1006584649, 2351174528, 844971309, 1393498279, 3862110838, 2569227497, 1861633108],
    ],
    [
      '0123456789abcdef',
      [3643898672, 1302437532, 3062173099, 2079858411, 918275193, 984434972, 1552021949, 1674540379],
    ],
    [
      'ffffffffffffffff',
      [4149980905, 3131759343, 1186148377, 2736333306, 3227873858, 1210736022, 3582539859, 4104175451],
    ],
  ])('Should match the reference C stream for seed=%s', (hex, expected) => {
    // Generated by composing the authors' splitmix64.c and xorshift128plus.c.
    // Read SplitMix64 twice into s[0] and s[1], then keep each next() output's low word.
    const rng = xorshift128plus(seed64FromHex(hex));
    expect(generateN(rng, expected.length)).toEqual(expected.map((value) => value | 0));
  });

  it('Should initialize both state words from SplitMix64', () => {
    // First two outputs of the reference SplitMix64 C implementation for seed=0.
    expect(xorshift128plus([0, 0]).getState()).toEqual(
      [0xe220a839, 0x7b1dcdaf, 0x6e789e6a, 0xa1b965f4].map((value) => value | 0),
    );
  });

  it('Should use the high seed word', () => {
    const low = xorshift128plus(seed64FromHex('0000000000000000'));
    const high = xorshift128plus(seed64FromHex('0000000100000000'));
    expect(low.getState()).not.toEqual(high.getState());
  });

  it('Should use distinct initialization rules for numeric and Seed64 seeds', () => {
    expect(xorshift128plus([0, 42]).getState()).not.toEqual(xorshift128plus(42).getState());
  });

  it('Should reject invalid Seed64 words', () => {
    expect(() => xorshift128plus([-1, 0])).toThrow(RangeError);
    expect(() => xorshift128plus([0, 2 ** 32])).toThrow(RangeError);
    expect(() => xorshift128plus([0, 0.5])).toThrow(RangeError);
    expect(() => xorshift128plus([0] as unknown as Seed64)).toThrow(RangeError);
  });

  it('Should return the same sequence given the same seed', () =>
    fc.assert(p.sameSeed64SameSequences(xorshift128plus)));
  it('Should support cloning and state restoration', () =>
    fc.assert(p.cloneAndRestoreSeed64(xorshift128plus, xorshift128plusFromState)));
  it('Should not depend on ordering between jump and next', () => fc.assert(p.seed64NoOrderNextJump(xorshift128plus)));
  it('Should not mutate or retain the seed tuple', () => fc.assert(p.doesNotRetainSeed64(xorshift128plus)));
});
